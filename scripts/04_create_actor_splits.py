"""
Create reproducible Actor splits for prompt optimization and evaluation.

Source pool (conversation-level, question-only):
  data/processed_mrbench/dev.csv   (136 rows)
  data/processed_mrbench/test.csv  (59 rows)
  Combined: 195 conversations from MRBench V2.

  dev.csv and test.csv are generic source files generated by prepare_mrbench.py.
  They are NOT the official Actor train/test files. The official files are below.

Leakage guard:
  Base conversation IDs appearing in calibration.csv, judge_dev.csv, or
  judge_test.csv are excluded from the Actor pool. The Judge was validated on
  historical tutor responses for those conversations; reusing the same student
  questions for Actor optimization could introduce subtle bias.

  Judge split row IDs have the form <conv_id>_<ModelName>. The base conv ID is
  recovered by stripping the last underscore-separated segment. Actor row IDs are
  bare conversation IDs (no underscore suffix), so no ambiguity arises.

Output files — all question-only, no tutor_response or human_* labels:

  A. Actor full splits
       actor_train.csv      — 80 rows  (Actor prompt optimization input)
       actor_test.csv       — 20 rows  (locked held-out evaluation; run once)

  B. Actor mini splits (subsets of the full splits, for fast prototyping)
       actor_mini_train.csv — 30 rows sampled from actor_train.csv
       actor_mini_test.csv  — 20 rows  (equals actor_test.csv; test is already mini-sized)

  These supersede the old ambiguous mini_dev.csv and mini_test.csv, which had
  unclear provenance and no documented generation step.

Split construction:
  actor_train + actor_test are chosen by repeated random sampling (SEED=42,
  MAX_STRATIFY_ATTEMPTS=1000). Each candidate split is scored by how closely its
  length-bucket distribution matches the eligible pool proportions. The best-scoring
  split is selected. This keeps short/medium/long questions roughly proportional
  across both train and test.

  actor_mini_train is sampled from actor_train using MINI_SEED=43.
  actor_mini_test equals actor_test (20 = 20 rows, no resampling needed).

Schema (all Actor files):
  id, student_question, target_learner_level, instruction_constraints, expected_rubric
"""

import csv
import random
import sys
from collections import Counter
from pathlib import Path

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

FULL_TRAIN_SIZE = 80
FULL_TEST_SIZE = 20
MINI_TRAIN_SIZE = 30
MINI_TEST_SIZE = 20   # equals FULL_TEST_SIZE; actor_mini_test = actor_test

SEED = 42
MINI_SEED = 43        # used to subsample actor_train → actor_mini_train
MAX_STRATIFY_ATTEMPTS = 1_000

ACTOR_FIELDNAMES = [
    "id",
    "student_question",
    "target_learner_level",
    "instruction_constraints",
    "expected_rubric",
]

_JUDGE_SPLIT_PATHS = [
    Path("data/processed_mrbench/calibration.csv"),
    Path("data/processed_mrbench/judge_dev.csv"),
    Path("data/processed_mrbench/judge_test.csv"),
]

_ACTOR_POOL_PATHS = [
    Path("data/processed_mrbench/dev.csv"),
    Path("data/processed_mrbench/test.csv"),
]

_BUCKET_KEYS = ["short", "medium", "long"]
_BUCKET_DISPLAY = {
    "short":  "short  (<500 chars)",
    "medium": "medium (500–1500 chars)",
    "long":   "long   (>1500 chars)",
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _base_id(full_id: str) -> str:
    """Strip _ModelName suffix from a judge-validation row ID."""
    return full_id.rsplit("_", 1)[0]


def _length_bucket(question: str) -> str:
    n = len(question)
    if n < 500:
        return "short"
    if n <= 1500:
        return "medium"
    return "long"


def _split_score(
    train: list[dict],
    test: list[dict],
    pool_buckets: Counter,
    pool_n: int,
) -> float:
    """
    Stratification quality score. Higher is better.

    Measures the total L1 distance between each split's length-bucket
    distribution and the eligible pool's distribution. Smaller distance
    (closer to 0) is better, so we negate it.
    """
    score = 0.0
    for split in [train, test]:
        n = len(split)
        if n == 0:
            return float("-inf")
        sb = Counter(_length_bucket(r["student_question"]) for r in split)
        for b in _BUCKET_KEYS:
            expected = pool_buckets.get(b, 0) / pool_n
            actual = sb.get(b, 0) / n
            score -= abs(actual - expected)
    return score


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def build_forbidden_base_ids(judge_split_paths: list[Path]) -> set[str]:
    """Return the set of base conversation IDs used in the given judge splits."""
    forbidden: set[str] = set()
    for path in judge_split_paths:
        if not path.exists():
            print(f"  WARNING: {path} not found — skipping for forbidden ID collection.")
            continue
        with path.open(encoding="utf-8") as f:
            for row in csv.DictReader(f):
                forbidden.add(_base_id(row["id"]))
    return forbidden


def load_actor_pool(pool_paths: list[Path]) -> list[dict]:
    """Load and concatenate actor rows from the given CSV paths, deduplicating by ID."""
    rows: list[dict] = []
    seen_ids: set[str] = set()
    for path in pool_paths:
        if not path.exists():
            sys.exit(f"ERROR: {path} not found. Run prepare_mrbench first.")
        with path.open(encoding="utf-8") as f:
            for row in csv.DictReader(f):
                if row["id"] in seen_ids:
                    print(f"  WARNING: duplicate actor ID {row['id']!r} skipped.")
                    continue
                seen_ids.add(row["id"])
                rows.append(row)
    return rows


def create_actor_splits(
    rows: list[dict],
    forbidden_base_ids: set[str],
    train_size: int,
    test_size: int,
    seed: int,
    max_attempts: int = MAX_STRATIFY_ATTEMPTS,
) -> tuple[list[dict], list[dict]]:
    """
    Filter eligible rows (excluding forbidden IDs), then find the best-scoring
    train/test split via repeated random sampling.

    Scoring favors splits whose length-bucket distributions are close to the
    eligible pool's distribution.

    Returns (train_rows, test_rows). Raises ValueError if the pool is too small.
    """
    eligible = [r for r in rows if r["id"] not in forbidden_base_ids]
    total_needed = train_size + test_size

    if len(eligible) < total_needed:
        raise ValueError(
            f"Only {len(eligible)} eligible rows after forbidden-ID exclusion, "
            f"but {total_needed} needed ({train_size} train + {test_size} test)."
        )

    pool_n = len(eligible)
    pool_buckets = Counter(_length_bucket(r["student_question"]) for r in eligible)

    rng = random.Random(seed)
    best_train: list[dict] = []
    best_test: list[dict] = []
    best_score = float("-inf")

    for _ in range(max_attempts):
        shuffled = eligible.copy()
        rng.shuffle(shuffled)
        train = shuffled[:train_size]
        test = shuffled[train_size : train_size + test_size]
        score = _split_score(train, test, pool_buckets, pool_n)
        if score > best_score:
            best_score = score
            best_train = train
            best_test = test

    return best_train, best_test


def sample_mini(rows: list[dict], size: int, seed: int) -> list[dict]:
    """
    Return a deterministic subsample of `size` rows from `rows`.

    If len(rows) == size, returns a copy unchanged (no shuffling needed).
    Raises ValueError if len(rows) < size.
    """
    if len(rows) < size:
        raise ValueError(
            f"Cannot sample {size} rows from a pool of {len(rows)}."
        )
    if len(rows) == size:
        return rows.copy()
    shuffled = rows.copy()
    random.Random(seed).shuffle(shuffled)
    return shuffled[:size]


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

def _print_diversity(label: str, rows: list[dict]) -> None:
    n = len(rows)
    print(f"\n{label} ({n} rows):")

    level_counts = Counter(r["target_learner_level"] for r in rows)
    print(f"  target_learner_level: {len(level_counts)} unique values")
    for val, cnt in level_counts.most_common(5):
        print(f"    {val!r:<50} {cnt:>3}")
    if len(level_counts) > 5:
        print(f"    ... ({len(level_counts) - 5} more unique values)")

    bucket_counts = Counter(_length_bucket(r["student_question"]) for r in rows)
    print(f"  student_question length:")
    for b in _BUCKET_KEYS:
        cnt = bucket_counts.get(b, 0)
        pct = cnt / n if n else 0
        print(f"    {_BUCKET_DISPLAY[b]}: {cnt:>3}  ({pct:.0%})")


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=ACTOR_FIELDNAMES, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote: {path}  ({len(rows)} rows)")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    print("=== Actor Split Construction ===\n")

    # --- Forbidden IDs from Judge validation splits ---
    forbidden = build_forbidden_base_ids(_JUDGE_SPLIT_PATHS)
    print(f"Forbidden base conv IDs (calibration + judge_dev + judge_test): {len(forbidden)}")

    # --- Source pool ---
    pool = load_actor_pool(_ACTOR_POOL_PATHS)
    excluded_count = sum(1 for r in pool if r["id"] in forbidden)
    eligible_count = len(pool) - excluded_count
    print(f"Source pool (dev.csv + test.csv): {len(pool)} rows")
    print(f"Excluded (judge-split base IDs):  {excluded_count}")
    print(f"Eligible for Actor splits:        {eligible_count}")

    # --- Full Actor splits (stratified) ---
    print(f"\nSearching for best-stratified split ({MAX_STRATIFY_ATTEMPTS} attempts, seed={SEED})…")
    try:
        actor_train, actor_test = create_actor_splits(
            pool, forbidden, FULL_TRAIN_SIZE, FULL_TEST_SIZE, SEED, MAX_STRATIFY_ATTEMPTS
        )
    except ValueError as exc:
        sys.exit(f"\nERROR: {exc}")

    # --- Mini Actor splits ---
    actor_mini_train = sample_mini(actor_train, MINI_TRAIN_SIZE, MINI_SEED)
    actor_mini_test = sample_mini(actor_test, MINI_TEST_SIZE, MINI_SEED)

    # --- Hard assertions ---
    assert len(actor_train) == FULL_TRAIN_SIZE
    assert len(actor_test) == FULL_TEST_SIZE
    assert len(actor_mini_train) == MINI_TRAIN_SIZE
    assert len(actor_mini_test) == MINI_TEST_SIZE

    train_ids = {r["id"] for r in actor_train}
    test_ids = {r["id"] for r in actor_test}
    mini_train_ids = {r["id"] for r in actor_mini_train}
    mini_test_ids = {r["id"] for r in actor_mini_test}

    assert not (train_ids & test_ids), "actor_train ∩ actor_test must be empty"
    assert mini_train_ids <= train_ids, "actor_mini_train must be a subset of actor_train"
    assert mini_test_ids <= test_ids, "actor_mini_test must be a subset of actor_test"

    for split_rows, label in [
        (actor_train, "actor_train"),
        (actor_test, "actor_test"),
        (actor_mini_train, "actor_mini_train"),
        (actor_mini_test, "actor_mini_test"),
    ]:
        ids = [r["id"] for r in split_rows]
        assert len(ids) == len(set(ids)), f"Duplicate IDs in {label}"
        for r in split_rows:
            assert r["id"] not in forbidden, f"Forbidden ID {r['id']!r} in {label}"

    # --- Overlap report ---
    print("\n--- Overlap audit ---")
    print(f"  actor_train ∩ actor_test:          {len(train_ids & test_ids)}  (expected 0)")
    print(f"  actor_mini_train ∩ actor_mini_test: {len(mini_train_ids & mini_test_ids)}  (expected 0)")
    print(f"  actor_mini_train ⊆ actor_train:     {mini_train_ids <= train_ids}  (expected True)")
    print(f"  actor_mini_test  ⊆ actor_test:      {mini_test_ids <= test_ids}  (expected True)")
    for split_ids, split_label in [
        (train_ids,      "actor_train     "),
        (test_ids,       "actor_test      "),
        (mini_train_ids, "actor_mini_train"),
        (mini_test_ids,  "actor_mini_test "),
    ]:
        for judge_label, judge_path in [
            ("calibration", _JUDGE_SPLIT_PATHS[0]),
            ("judge_dev",   _JUDGE_SPLIT_PATHS[1]),
            ("judge_test",  _JUDGE_SPLIT_PATHS[2]),
        ]:
            if judge_path.exists():
                judge_base = {_base_id(r["id"]) for r in csv.DictReader(judge_path.open(encoding="utf-8"))}
                cnt = len(split_ids & judge_base)
                print(f"  {split_label} ∩ {judge_label} base IDs: {cnt}  (expected 0)")

    # --- Diversity reports ---
    _print_diversity("ACTOR_TRAIN", actor_train)
    _print_diversity("ACTOR_TEST", actor_test)
    _print_diversity("ACTOR_MINI_TRAIN", actor_mini_train)
    _print_diversity("ACTOR_MINI_TEST", actor_mini_test)

    # --- Write ---
    out_dir = Path("data/processed_mrbench")
    _write_csv(out_dir / "actor_train.csv",      actor_train)
    _write_csv(out_dir / "actor_test.csv",       actor_test)
    _write_csv(out_dir / "actor_mini_train.csv", actor_mini_train)
    _write_csv(out_dir / "actor_mini_test.csv",  actor_mini_test)

    print("\nNote: actor_mini_train.csv / actor_mini_test.csv supersede the old")
    print("      mini_dev.csv / mini_test.csv (which had unclear provenance).")
    print("\nAll assertions passed.")


if __name__ == "__main__":
    main()
